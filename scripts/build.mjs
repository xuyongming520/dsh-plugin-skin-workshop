// A deliberately tiny, dependency-free builder for this plugin's own modules.
// Supported source syntax: named relative imports + exported declarations only.
// Runtime React is supplied by DSH, not bundled or installed by this script.
import { readFile, writeFile } from 'node:fs/promises'
import vm from 'node:vm'

const root = new URL('../', import.meta.url)
const names = ['model', 'backgrounds', 'renderer', 'store', 'files', 'ui-style', 'ui', 'plugin']
const parts = []
for (const name of names) {
  const source = await readFile(new URL(`src/${name}.js`, root), 'utf8')
  const compiled = source
    .replace(/^import\s+\{[^}]+\}\s+from\s+['"]\.\/[^'"]+['"];?\s*$/gm, '')
    .replace(/^export\s+(?=(?:const|let|function|async function|class)\b)/gm, '')
  if (/^\s*(?:import|export)\s/m.test(compiled)) throw new Error(`Unsupported module syntax in ${name}; update the builder explicitly.`)
  parts.push(`// ----- src/${name}.js -----\n${compiled}`)
}
const result = `// Generated by scripts/build.mjs. Edit src/ instead. No external runtime bundle.\nwindow.__ModuleLoader__.load({\n  id: '@local/violet-skin',\n  factory: (require) => {\n'use strict';\n${parts.join('\n\n')}\nreturn createPlugin(require);\n  },\n});\n`
new vm.Script(result, { filename: 'client.js' })
await writeFile(new URL('client.js', root), result, 'utf8')
console.log(`Built client.js (${Buffer.byteLength(result).toLocaleString()} bytes) from ${names.length} modules.`)
